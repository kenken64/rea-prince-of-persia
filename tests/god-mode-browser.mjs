import assert from 'node:assert/strict';
import {mkdirSync,writeFileSync} from 'node:fs';
import {dirname,resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'playwright');
const output=resolve(dirname(fileURLToPath(import.meta.url)),'../../analysis/validation');
mkdirSync(output,{recursive:true});
const browser=await chromium.launch({headless:true,...(process.env.CHROME_PATH?{executablePath:process.env.CHROME_PATH}:{})});
const errors=[];
try {
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  page.on('pageerror',e=>errors.push(e.message));
  page.on('response',r=>{if(r.status()>=400)errors.push(`HTTP ${r.status()} ${r.url()}`);});
  const url=process.env.TEST_URL||'http://127.0.0.1:8000';
  await page.goto(url,{waitUntil:'networkidle'});await page.waitForFunction(()=>window.popStudy?.ready);
  const toggle=page.locator('#god-mode');
  assert.equal(await toggle.getAttribute('aria-pressed'),'false');
  assert.equal(await toggle.isEnabled(),true);
  await toggle.focus();await page.keyboard.press('Space');
  assert.equal(await toggle.getAttribute('aria-pressed'),'true','button supports keyboard activation');
  assert.equal(await page.evaluate(()=>popStudy.game.game_get_god_mode()),1);
  await page.click('#start');await page.keyboard.press('KeyP');
  const protectedState=await page.evaluate(()=>{
    const g=popStudy.game;g.game_set_paused(0);
    for(let p=0;p<30;p++)g.game_edit_tile(0,1,p,p>=20?1:0);
    for(let d=0;d<4;d++)g.game_edit_link(0,1,d,0);
    g.game_edit_guard(0,1,255);g.game_reset();
    g.game_edit_tile(0,1,23,2);g.game_set_player(1,112,184,1);
    const before=g.game_get_time_left();g.game_update(120);g.game_set_paused(1);popStudy.draw();
    return {before,after:g.game_get_time_left(),health:g.game_get_health(),dead:!!(g.game_get_flags()&1)};
  });
  assert.equal(protectedState.before,protectedState.after);assert.equal(protectedState.health,3);assert.equal(protectedState.dead,false);
  await page.locator('#game-card').screenshot({path:resolve(output,'god-mode-desktop.png')});
  await toggle.click();assert.equal(await toggle.getAttribute('aria-pressed'),'false');
  const vulnerable=await page.evaluate(()=>{const g=popStudy.game;g.game_set_paused(0);g.game_step();g.game_set_paused(1);return !!(g.game_get_flags()&1);});
  assert.equal(vulnerable,true,'turning mode off restores lethal spikes');
  await toggle.click();
  assert.equal(await page.evaluate(()=>popStudy.game.game_get_flags()&1),0,'enabling revives a fallen prince');
  await page.click('#restart');assert.equal(await toggle.getAttribute('aria-pressed'),'true');
  await page.selectOption('#level-select','3');
  assert.equal(await page.evaluate(()=>popStudy.game.game_get_god_mode()),1,'level change preserves toggle');
  await page.click('#fullscreen');await page.waitForFunction(()=>document.fullscreenElement?.id==='game-card');
  assert.equal(await toggle.isVisible(),true);await toggle.click();
  assert.equal(await toggle.getAttribute('aria-pressed'),'false','toggle works in fullscreen');
  await page.click('#fullscreen');
  const mobile=await browser.newPage({viewport:{width:320,height:700},isMobile:true,hasTouch:true});
  mobile.on('pageerror',e=>errors.push(e.message));
  await mobile.goto(url,{waitUntil:'networkidle'});await mobile.waitForFunction(()=>window.popStudy?.ready);
  await mobile.tap('#start');await mobile.tap('#god-mode');
  assert.equal(await mobile.locator('#god-mode').getAttribute('aria-pressed'),'true');
  const layout=await mobile.evaluate(()=>{
    const card=document.querySelector('#game-card').getBoundingClientRect(),button=document.querySelector('#god-mode').getBoundingClientRect();
    return {overflow:document.documentElement.scrollWidth>innerWidth,cardHeight:card.height,viewport:innerHeight,buttonFits:button.left>=card.left&&button.right<=card.right};
  });
  assert.equal(layout.overflow,false);assert.equal(layout.buttonFits,true);assert.ok(layout.cardHeight<=layout.viewport);
  await mobile.locator('#game-card').screenshot({path:resolve(output,'god-mode-mobile.png')});
  await mobile.reload({waitUntil:'networkidle'});await mobile.waitForFunction(()=>window.popStudy?.ready);
  assert.equal(await mobile.locator('#god-mode').getAttribute('aria-pressed'),'false','new page starts with mode off');
  assert.deepEqual(errors,[]);
  const result={passed:true,checks:['keyboard toggle','full health','spike immunity','frozen clock','disable restores damage','revive','restart and level persistence','fullscreen toggle','mobile touch and viewport fit','reload defaults off'],protectedState,layout,errors};
  writeFileSync(resolve(output,'god-mode-browser.json'),JSON.stringify(result,null,2)+'\n');console.log(JSON.stringify(result,null,2));
}finally{await browser.close();}
