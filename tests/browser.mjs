import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const output=resolve('../analysis/validation');mkdirSync(output,{recursive:true});
const browser=await chromium.launch({headless:true,...(process.env.CHROME_PATH?{executablePath:process.env.CHROME_PATH}:{})});
const errors=[];
const page=await browser.newPage({viewport:{width:1440,height:1100},deviceScaleFactor:1});
page.on('pageerror',e=>errors.push(e.message));
page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
page.on('response',r=>{if(r.status()>=400)errors.push(`HTTP ${r.status()} ${r.url()}`);});
try {
  await page.goto(process.env.TEST_URL||'http://127.0.0.1:8000',{waitUntil:'networkidle'});
  await page.waitForFunction(()=>window.popStudy?.ready);
  await page.screenshot({path:resolve(output,'desktop-ready.png'),fullPage:true});
  assert.equal(await page.locator('#level-select option').count(),14);
  assert.equal(await page.locator('.room-tile').count(),24);
  await page.click('#start');
  assert.equal(await page.locator('#game-overlay').isVisible(),false);
  await page.waitForTimeout(1100);
  const initial=await page.evaluate(()=>({x:popStudy.game.game_get_player_x(),y:popStudy.game.game_get_player_y(),room:popStudy.game.game_get_room()}));
  await page.keyboard.down('ArrowRight');await page.waitForTimeout(250);await page.keyboard.up('ArrowRight');
  const moved=await page.evaluate(()=>({x:popStudy.game.game_get_player_x(),y:popStudy.game.game_get_player_y(),room:popStudy.game.game_get_room()}));
  assert.ok(moved.x!==initial.x||moved.room!==initial.room,'keyboard input moves C simulation');
  await page.keyboard.press('Space');await page.waitForTimeout(100);
  await page.keyboard.press('KeyP');
  const tick=await page.evaluate(()=>popStudy.game.game_get_tick());await page.waitForTimeout(160);
  assert.equal(await page.evaluate(()=>popStudy.game.game_get_tick()),tick,'pause stops C ticks');
  await page.screenshot({path:resolve(output,'desktop-playing.png'),fullPage:true});
  await page.keyboard.press('KeyP');
  await page.selectOption('#level-select','7');
  assert.equal(await page.evaluate(()=>popStudy.game.game_get_level()),7);
  await page.click('[data-tab="graphics"]');assert.equal(await page.locator('#graphics-panel').isVisible(),true);
  await page.click('[data-tab="code"]');assert.equal(await page.locator('#code-panel').isVisible(),true);
  await page.click('[data-tab="map"]');
  await page.locator('.room-tile:not(.absent)').nth(2).click();
  await page.click('#visit-room');assert.ok(await page.evaluate(()=>popStudy.game.game_get_room()>=1));
  await page.selectOption('#level-select','0');
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:resolve(output,'mobile-playing.png'),fullPage:true});
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1);
  assert.equal(overflow,false,'mobile layout has no horizontal overflow');
  const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true,deviceScaleFactor:1});
  mobile.on('pageerror',e=>errors.push(e.message));
  await mobile.goto(process.env.TEST_URL||'http://127.0.0.1:8000',{waitUntil:'networkidle'});
  await mobile.waitForFunction(()=>window.popStudy?.ready);
  await mobile.tap('#start');
  assert.equal(await mobile.locator('.touch-controls').isVisible(),true,'touch controls appear on a touch device');
  const box=await mobile.locator('[data-key="2"]').boundingBox();
  const mobileInput=await mobile.context().newCDPSession(mobile);
  const touchX=await mobile.evaluate(()=>popStudy.game.game_get_player_x());
  await mobileInput.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:box.x+box.width/2,y:box.y+box.height/2}]});
  await mobile.waitForTimeout(250);
  await mobileInput.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
  assert.ok(await mobile.evaluate(()=>popStudy.game.game_get_player_x())>touchX,'touch input moves C simulation');
  await mobile.screenshot({path:resolve(output,'mobile-touch.png'),fullPage:true});
  await mobile.close();
  assert.deepEqual(errors,[]);
  const results={passed:true,checks:['Wasm boot','14-level selector','24-room map','start','keyboard movement','jump input','pause','level select','graphics/code tabs','room exploration','mobile overflow','touch controls','no browser or HTTP errors'],initial,moved,errors};
  writeFileSync(resolve(output,'browser.json'),JSON.stringify(results,null,2)+'\n');
  console.log(JSON.stringify(results,null,2));
} finally {await browser.close();}
